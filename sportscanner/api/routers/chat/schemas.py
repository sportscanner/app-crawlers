from datetime import datetime
from typing import Any, List, Literal, Optional

from pydantic import BaseModel, Field


class AgentChatMessage(BaseModel):
    role: Literal["user", "assistant", "system"] = Field(
        ...,
        description="Message role in the running chat transcript.",
    )
    content: str = Field(
        ...,
        min_length=1,
        description="Message text content.",
    )


class AgentChatRequest(BaseModel):
    messages: List[AgentChatMessage] = Field(
        ...,
        min_length=1,
        description=(
            "Ordered conversation transcript. Include prior turns for context; "
            "the final message should usually be the latest user query."
        ),
    )
    chat_session_id: Optional[str] = Field(
        default=None,
        description=(
            "Optional existing chat session id. Provide this to continue a "
            "previous conversation."
        ),
    )


class AgentChatResponse(BaseModel):
    reply: str = Field(..., description="Assistant response text.")
    follow_up_questions: List[str] = Field(
        default_factory=list,
        description=(
            "Two suggested follow-up questions generated by the agent for "
            "click-to-ask actions in the chat UI."
        ),
    )
    used_tools: List[str] = Field(
        default_factory=list,
        description="MCP tool names invoked while answering this request.",
    )
    model: str = Field(..., description="LLM model used by the ADK-powered agent.")
    ui_blocks: Optional[list[dict[str, Any]]] = Field(
        default=None,
        description=(
            "Optional structured UI blocks (for example venue cards) that the frontend "
            "can render directly."
        ),
    )
    chat_session_id: Optional[str] = Field(
        default=None,
        description="Chat session id associated with this exchange (if persisted).",
    )
    error: Optional[str] = Field(
        default=None,
        description="Present only when request could not be fulfilled.",
    )


class AgentChatSessionCreateRequest(BaseModel):
    title: Optional[str] = Field(
        default=None,
        description="Optional title for the new chat session.",
    )


class AgentChatSessionSummary(BaseModel):
    id: str
    title: Optional[str] = None
    created_at: datetime
    updated_at: datetime
    message_count: int = 0
    last_message_preview: Optional[str] = None


class AgentChatSessionMessage(BaseModel):
    id: int
    role: Literal["user", "assistant", "system"]
    content: str
    follow_up_questions: Optional[List[str]] = Field(
        default=None,
        description=(
            "Optional follow-up action suggestions attached to this assistant message."
        ),
    )
    used_tools: List[str] = Field(default_factory=list)
    model: Optional[str] = None
    ui_blocks: Optional[list[dict[str, Any]]] = Field(default=None)
    created_at: datetime


class AgentChatSessionDetail(BaseModel):
    id: str
    title: Optional[str] = None
    created_at: datetime
    updated_at: datetime
    messages: List[AgentChatSessionMessage] = Field(default_factory=list)


# --- Eval schemas ---


class ToolCallRecordSchema(BaseModel):
    tool: str
    input: dict[str, Any]
    output: Any
    timestamp_utc: str
    duration_ms: float
    guardrail_fired: bool = False
    guardrail_original_input: Optional[dict[str, Any]] = None
    error: Optional[str] = None


class AgentTrajectorySchema(BaseModel):
    query: str
    tool_calls: List[ToolCallRecordSchema] = Field(default_factory=list)
    final_reply: str = ""
    started_at: str = ""
    completed_at: str = ""
    total_duration_ms: float = 0.0


class JudgeScoresSchema(BaseModel):
    response_correctness: float = 0.0
    tool_efficiency: float = 0.0
    gap_handling: float = 0.0
    completeness: float = 0.0
    overall: float = 0.0
    reason: str = ""
    error: Optional[str] = None


class AgentEvalRequest(BaseModel):
    query: str = Field(..., min_length=1, description="User query to evaluate.")
    judge_model: Optional[str] = Field(
        default=None,
        description=(
            "LiteLLM model string for the judge (e.g. 'openai/gpt-4o'). "
            "Defaults to SPORTSCANNER_AGENT_MODEL."
        ),
    )


class AgentEvalResponse(BaseModel):
    query: str
    reply: str
    used_tools: List[str] = Field(default_factory=list)
    trajectory: AgentTrajectorySchema
    judge: JudgeScoresSchema
    model: str
